// Writes src/environments/environment.production.ts from the API_URL environment
// variable, so the deployed client points at the deployed API without the domain
// ever being committed to the repository.
//
// Netlify runs this before `ng build`. It fails loudly when API_URL is missing:
// the same fail-fast rule the API applies to its own configuration, for the same
// reason — a build that silently ships the wrong host is worse than no build.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const apiUrl = process.env.API_URL;

if (!apiUrl) {
  console.error(
    'API_URL is not set. Set it to the deployed API origin, e.g.\n' +
      '  API_URL=https://labtrack-api.up.railway.app npm run config:api-url -w apps/web',
  );
  process.exit(1);
}

// CI providers mask environment values in their logs, so echoing the offending
// value prints '****' and tells the reader nothing. These messages describe what
// a correct value looks like instead.
let parsed;
try {
  parsed = new URL(apiUrl);
} catch {
  console.error(
    [
      'API_URL is not a valid URL.',
      'It must include the scheme, for example https://labtrack-api.up.railway.app',
      'A bare host such as labtrack-api.up.railway.app is the usual cause.',
    ].join('\n'),
  );
  process.exit(1);
}

if (parsed.protocol !== 'https:' && parsed.hostname !== 'localhost') {
  console.error(
    `API_URL must use https outside localhost, but its scheme is '${parsed.protocol}'.`,
  );
  process.exit(1);
}

// Trailing slashes would produce '//auth/login' once the client concatenates paths.
const origin = apiUrl.replace(/\/+$/, '');

const target = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'src',
  'environments',
  'environment.production.ts',
);

writeFileSync(
  target,
  `// Generated by scripts/write-production-env.mjs. Do not edit by hand.\n` +
    `export const environment = { production: true, apiUrl: '${origin}' };\n`,
  'utf8',
);

console.log(`environment.production.ts written with apiUrl ${origin}`);
